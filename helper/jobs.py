"""Bounded background jobs, cancellation, and atomic recovery checkpoints."""
from copy import deepcopy
import json
import os
from pathlib import Path
import re
import threading
import time
from uuid import uuid4

from helper.pipeline import scrape_news
from helper.http_client import close_session

_slots = threading.BoundedSemaphore(2)
_store_lock = threading.RLock()
DEFAULT_STORE = Path(__file__).resolve().parents[1] / "data" / "runs"


def list_checkpoints(directory=DEFAULT_STORE):
    with _store_lock:
        files = []
        for path in Path(directory).glob("*.json"):
            if re.fullmatch(r"[a-f0-9]{32}\.json", path.name):
                try:
                    files.append((path.stat().st_mtime, path))
                except FileNotFoundError:
                    continue
        return [path for _, path in sorted(files, reverse=True)]


def save_checkpoint(payload, directory=DEFAULT_STORE):
    with _store_lock:
        _save_checkpoint(payload, directory)


def _save_checkpoint(payload, directory):
    run_id = payload["metadata"]["run_id"]
    if not re.fullmatch(r"[a-f0-9]{32}", run_id):
        raise ValueError("ID checkpoint tidak valid.")
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{run_id}.json"
    temp = directory / f"{run_id}.json.tmp"
    temp.write_text(json.dumps(payload, ensure_ascii=True), encoding="utf-8")
    os.replace(temp, path)
    # Only checkpoints generated by this app are eligible for retention cleanup.
    files = list_checkpoints(directory)
    for old in files[20:]:
        try:
            old.unlink()
        except FileNotFoundError:
            pass


def load_checkpoint(path):
    with _store_lock:
        return _load_checkpoint(path)


def _load_checkpoint(path):
    path = Path(path)
    if path.stat().st_size > 256 * 1024 * 1024:
        raise ValueError("File hasil tersimpan terlalu besar untuk dibuka.")
    result = json.loads(path.read_text(encoding="utf-8"))
    if (not isinstance(result, dict) or not isinstance(result.get("data"), list)
            or not isinstance(result.get("reports"), list) or not isinstance(result.get("metadata"), dict)):
        raise ValueError("Format file hasil tersimpan tidak bisa dibaca.")
    if result["metadata"].get("state") == "running":
        result["metadata"]["state"] = "interrupted"
        for report in result["reports"]:
            if not report.get("coverage_complete"):
                report.update(status="partial" if report.get("count") else "failed", stop_reason="INTERRUPTED")
    return result


class ScrapeJob:
    def __init__(self, start_date, end_date, sources, *, store=DEFAULT_STORE):
        self.run_id = uuid4().hex
        self.start_date, self.end_date, self.sources = start_date, end_date, list(sources)
        self.store = store
        self.cancel = threading.Event()
        self.done = threading.Event()
        self.lock = threading.Lock()
        self.progress, self.note = 0.0, "Menyiapkan proses."
        self.result, self.error, self.storage_error = None, None, None
        self._last_save = 0
        self._started = False

    def start(self):
        if self._started:
            raise RuntimeError("Proses ini sudah pernah dimulai.")
        if not _slots.acquire(blocking=False):
            raise RuntimeError("Ada dua pencarian yang masih berjalan. Tunggu salah satunya selesai, lalu coba lagi.")
        try:
            self._started = True
            threading.Thread(target=self._run, daemon=True, name=f"scrape-{self.run_id[:8]}").start()
        except Exception:
            _slots.release()
            raise

    def _progress(self, fraction, note):
        with self.lock:
            self.progress, self.note = fraction, note

    def _checkpoint(self, result):
        with self.lock:
            self.result = deepcopy(result)
        now = time.monotonic()
        if now - self._last_save >= 2 or result["metadata"]["state"] != "running":
            try:
                save_checkpoint(result, self.store)
                self._last_save = now
            except OSError as error:
                self.storage_error = f"Hasil belum bisa disimpan di perangkat ({type(error).__name__}). Datanya masih tersedia di halaman ini."

    def snapshot(self):
        with self.lock:
            return self.progress, self.note, deepcopy(self.result)

    def _run(self):
        try:
            result = scrape_news(self.start_date, self.end_date, self.sources, progress=self._progress,
                                 checkpoint=self._checkpoint, cancel=self.cancel, run_id=self.run_id)
            self._checkpoint(result)
        except Exception as error:
            self.error = f"Proses gagal: {error}"
        finally:
            close_session()
            self.done.set()
            _slots.release()
